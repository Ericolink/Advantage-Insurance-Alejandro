import type { Metadata } from "next";
import { alternatePaths, type Route } from "@/config/routes";
import { site } from "@/config/site";
import { brandName } from "@/config/visibility";
import type { Locale } from "@/config/types";
import { localeTags } from "@/lib/i18n";

interface PageMeta {
  locale: Locale;
  route: Route;
  title: string;
  description: string;
  /** Use the title as-is instead of the "%s | Brand" template (home page). */
  absoluteTitle?: boolean;
  /** Keep this page out of search results (unapproved drafts, pending services). */
  noindex?: boolean;
}

/** Title, description, canonical, hreflang (with x-default) and Open Graph for one page. */
export function pageMetadata({ locale, route, title, description, absoluteTitle, noindex }: PageMeta): Metadata {
  const paths = alternatePaths(route, site);
  return {
    title: absoluteTitle ? { absolute: title } : title,
    description,
    ...(noindex && { robots: { index: false, follow: true } }),
    alternates: {
      canonical: paths[locale],
      languages: { [localeTags.en]: paths.en, [localeTags.es]: paths.es, "x-default": paths.en },
    },
    openGraph: {
      type: route.kind === "home" ? "website" : "article",
      siteName: brandName(site),
      title,
      description,
      url: paths[locale],
      locale: localeTags[locale].replace("-", "_"),
      alternateLocale: [localeTags[locale === "en" ? "es" : "en"].replace("-", "_")],
      // Generated by app/[lang]/opengraph-image.tsx; listed explicitly so inner pages keep it.
      images: [{ url: `/${locale}/opengraph-image`, width: 1200, height: 630, alt: brandName(site) }],
    },
  };
}
